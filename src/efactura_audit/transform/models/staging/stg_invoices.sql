-- One row per invoice or credit note, with the amount every check and report uses (spend_ron).
select
    invoice_key,
    coalesce(anaf_id, '') as anaf_id,
    number,
    type_code,
    is_credit_note,
    issue_date,
    due_date,
    currency,
    supplier_cui,
    supplier_vat_id,
    supplier_name,
    supplier_reg_no,
    supplier_iban,
    supplier_city,
    buyer_cui,
    buyer_name,
    line_total,
    tax_exclusive,
    tax_total,
    tax_inclusive,
    payable,
    fx_to_ron,
    amount_ron,
    coalesce(amount_ron, payable) as spend_ron,
    note,
    source_file,
    xml_sha256,
    imported_at
from {{ source('raw', 'invoices') }}
